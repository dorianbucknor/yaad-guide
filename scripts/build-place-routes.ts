// Generates supabase/migrations/20261109000200_place_routes.sql from the places
// seeded in 20261109000100_places.sql. Distances are estimates (straight line
// times a road factor, see src/lib/move/config.ts) until routed data replaces them.
// Run: node scripts/build-place-routes.ts
import { readFileSync, writeFileSync } from "node:fs";

import { estimateRoute } from "../src/lib/move/distance";

const source = readFileSync("supabase/migrations/20261109000100_places.sql", "utf8");
const rows = [
  ...source.matchAll(
    /\('([a-z0-9-]+)', '(?:[^']|'')+', '[a-z_]+', '(?:[^']|'')+', (-?\d+\.\d+), (-?\d+\.\d+)\)/g,
  ),
].map((m) => ({ slug: m[1], lat: Number(m[2]), lng: Number(m[3]) }));

if (rows.length < 25) throw new Error(`Expected at least 25 places, found ${rows.length}`);

const values: string[] = [];
for (let i = 0; i < rows.length; i++) {
  for (let j = i + 1; j < rows.length; j++) {
    const [a, b] = rows[i].slug < rows[j].slug ? [rows[i], rows[j]] : [rows[j], rows[i]];
    const { km, minutes } = estimateRoute(a, b);
    values.push(`  ('${a.slug}', '${b.slug}', ${km.toFixed(1)}, ${minutes})`);
  }
}

const sql = `-- Estimated driving distance and time between every pair of places.
-- Generated by scripts/build-place-routes.ts; do not edit by hand.
-- km is straight-line distance times a road factor, so every row is marked estimated.

create table public.place_routes (
  from_place_id uuid not null references public.places (id) on delete cascade,
  to_place_id uuid not null references public.places (id) on delete cascade,
  km numeric(7, 1) not null check (km >= 0),
  minutes integer not null check (minutes >= 0),
  estimated boolean not null default true,
  primary key (from_place_id, to_place_id),
  check (from_place_id < to_place_id)
);

alter table public.place_routes enable row level security;
create policy place_routes_select on public.place_routes
  for select to anon, authenticated using (true);

revoke all on public.place_routes from anon, authenticated;
grant select on public.place_routes to anon, authenticated;

-- Pairs are listed by slug; ids are put in order (least, greatest) when inserted.
insert into public.place_routes (from_place_id, to_place_id, km, minutes)
select least(a.id, b.id), greatest(a.id, b.id), p.km, p.minutes
from (values
${values.join(",\n")}
) as p (slug_a, slug_b, km, minutes)
join public.places a on a.slug = p.slug_a
join public.places b on b.slug = p.slug_b;
`;

writeFileSync("supabase/migrations/20261109000200_place_routes.sql", sql);
console.log(`Wrote ${values.length} routes for ${rows.length} places`);
